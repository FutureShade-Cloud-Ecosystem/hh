// The no-hand-written-wire-type scan. Two checks:
// 1. every file under src/gen carries the generated marker as its first line,
//    naming the generator and the document;
// 2. no TypeScript type named by the document's schemas is defined outside
//    src/gen: the wire vocabulary lives in generated code only.
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SCHEMA_NAMES } from "../src/gen/manifest.ts";

const packageDir = dirname(dirname(fileURLToPath(import.meta.url)));
const genDir = join(packageDir, "src", "gen");
const MARKER = "// Generated by scripts/gen-client/gen-client.mjs from core/api/openapi.yaml. DO NOT EDIT.";

const tsFilesUnder = (dir) => {
  const found = [];
  for (const entry of readdirSync(dir)) {
    if (entry === "gen" && dir === join(packageDir, "src")) continue;
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) found.push(...tsFilesUnder(p));
    else if (entry.endsWith(".ts")) found.push(p);
  }
  return found;
};

test("every generated file carries the generated marker as its first line", (t) => {
  const files = readdirSync(genDir).filter((f) => f.endsWith(".ts"));
  assert.ok(files.length >= 57, `the generated tree is populated (${files.length} files)`);
  for (const file of files) {
    const first = readFileSync(join(genDir, file), "utf8").split("\n")[0];
    assert.equal(first, MARKER, `${file} first line is the generated marker`);
  }
});

test("no schema-named type is declared outside src/gen", (t) => {
  const names = new Set(SCHEMA_NAMES);
  const offenders = [];
  // The package's hand-written TypeScript: the runtime modules (test/ holds
  // only plain .mjs, which cannot declare a TypeScript type).
  for (const file of tsFilesUnder(join(packageDir, "src"))) {
    const source = readFileSync(file, "utf8");
    for (const m of source.matchAll(/\b(?:type|interface|class|enum)\s+([A-Za-z_$][\w$]*)/g)) {
      if (names.has(m[1])) offenders.push(`${file}: declares ${m[1]}`);
    }
  }
  assert.deepEqual(offenders, [], "the wire vocabulary stays in generated code");
});

test("the generated manifest agrees with the generated types module", (t) => {
  const types = readFileSync(join(genDir, "types.ts"), "utf8");
  const declared = new Set([...types.matchAll(/^export type ([\w$]+) =/gm)].map((m) => m[1]));
  assert.equal(declared.size, SCHEMA_NAMES.length, "one declared type per manifest schema name");
  for (const name of SCHEMA_NAMES) {
    assert.ok(declared.has(name), `${name} is declared in types.ts`);
  }
  assert.equal(declared.has("Error"), true, "the contract's Error envelope is a wire type");
});
