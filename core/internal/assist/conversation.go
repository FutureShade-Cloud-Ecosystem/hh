package assist

// conversation.go, DIB-478. Multi-turn depth WITHOUT a schema change, and without the server
// remembering anything.
//
// -----------------------------------------------------------------------------------------------
// THE SERVER STAYS STATELESS. THE TRANSCRIPT TRAVELS.
// -----------------------------------------------------------------------------------------------
// The frontend already holds the transcript, it renders it. So the chat request carries the recent
// turns and the server holds nothing between calls. Three consequences, all of them the reason this
// is the design and not a conversations table:
//
//   - NO NEW MIGRATION. 0160 is not this ticket's to take. A conversation store is a retention
//     policy, an export obligation and a deletion path, and none of those are decisions a chat
//     feature should make on its way past. (Parked, with the design note, in NOTES-FIX-478.md.)
//   - NO CROSS-USER STATE. There is nothing on the service that could leak one person's context
//     into another's, in the same way StubProvider holds nothing between calls.
//   - THE WINDOW IS BOUNDED AND THE BOUND IS ENFORCED SERVER-SIDE. A client that posts two hundred
//     turns gets twelve considered. An unbounded window is an unbounded bill and an unbounded body.
//
// -----------------------------------------------------------------------------------------------
// WHAT RESOLUTION READS, AND WHAT IT REFUSES TO READ
// -----------------------------------------------------------------------------------------------
// It reads INVOCATIONS: which command ran, with which arguments. Not prose.
//
// That distinction is the whole of this file's claim to determinism. A resolver that re-read its own
// previous SENTENCES to work out what "it" meant would be parsing English generated by a provider
// that may be swapped out, the answer to "what does 'it' refer to" would change when the vendor
// changed. An invocation is a fact the SERVER produced, recorded exactly as it ran, and it is the
// same fact whether the sentence around it was written by the stub or by a model.
//
// So every answer records what ran (Answer.Ran), the frontend echoes it back on the next turn, and
// resolution is a pure function over that list. With no provider at all, resolution still works.

import "strings"

// WindowTurns bounds the conversation the server will consider: the last twelve messages.
//
// TWELVE, and the number is a judgement with two sides. Six (the old provider-history bound) is
// enough for one follow-up and loses the thread on "…and what about Kingston?" three questions
// later, which is exactly the depth this ticket exists to add. Fifty would carry a whole morning's
// context and would also re-bill a whole morning's tokens on every turn, the classic quadratic
// chat invoice. Twelve is about four question-and-answer pairs, which is the length of a real
// counter conversation before the subject genuinely changes.
//
// The PROVIDER still sees maxHistory (service.go): what the resolver may reason over and what is
// worth paying to re-send are different bounds, and collapsing them would tie a cost decision to a
// correctness one.
const WindowTurns = 12

// Invocation is ONE command that ran, with the arguments it ran with.
//
// This is the atom of conversational memory. It is written by the service after Registry.Run
// succeeds, so an invocation in the history is, by construction, a command the caller was ALLOWED
// to run at the time it ran. That does not make it allowed now (roles change, administrators switch
// commands off), which is why every resolved follow-up goes back through Registry.Run rather than
// being trusted because it worked last time.
type Invocation struct {
	Command string `json:"command"`
	Args    Args   `json:"args"`
}

// Window is the bounded, server-side view of the conversation the client posted.
type Window struct {
	Turns []Message
}

// NewWindow trims a posted history to the last WindowTurns messages.
//
// It is deliberately NOT validating that the turns are well-formed or that the invocations in them
// really happened. It cannot: the client could post anything. What protects the invariant is that
// nothing in a window grants authority, a forged Invocation naming "ar.aging" resolves to a call
// that is then run through Registry.Run as the asking user and refused exactly as it would be if
// the person had typed it. The window can change what is ASKED. It cannot change what is ALLOWED.
func NewWindow(h []Message) Window {
	if len(h) <= WindowTurns {
		return Window{Turns: append([]Message(nil), h...)}
	}
	return Window{Turns: append([]Message(nil), h[len(h)-WindowTurns:]...)}
}

// Invocations lists every command recorded in the window, OLDEST FIRST.
func (w Window) Invocations() []Invocation {
	var out []Invocation
	for _, m := range w.Turns {
		out = append(out, m.Ran...)
	}
	return out
}

// LastInvocation is the most recent command that ran, if any. It is the base a follow-up is built
// on: "and last week?" means "the thing I just asked, with a different week".
func (w Window) LastInvocation() (Invocation, bool) {
	for i := len(w.Turns) - 1; i >= 0; i-- {
		ran := w.Turns[i].Ran
		for j := len(ran) - 1; j >= 0; j-- {
			if strings.TrimSpace(ran[j].Command) != "" {
				return ran[j], true
			}
		}
	}
	return Invocation{}, false
}

// Entities is the conversation's entity memory: for each argument NAME, the freshest value anyone
// asked about.
//
// "Show me Brussels Block stock" records product=Brussels Block. "What about Kingston?" then runs
// stock.lookup with product=Brussels Block AND branch=Kingston, and the map now holds both, so a
// third turn ("when's it arriving?") still knows the product two questions later.
//
// FRESHEST WINS, AND EMPTY NEVER OVERWRITES. An invocation that ran without a customer does not
// erase the customer from memory: a person who asks about stock in the middle of an account
// conversation has not stopped talking about the account. What clears memory is falling out of the
// twelve-turn window, which is the same thing as the subject having genuinely changed.
func (w Window) Entities() map[string]string {
	out := map[string]string{}
	for _, inv := range w.Invocations() {
		for k, v := range inv.Args {
			if strings.TrimSpace(v) == "" {
				continue
			}
			out[k] = strings.TrimSpace(v)
		}
	}
	return out
}

// Entity is one remembered argument value.
func (w Window) Entity(name string) (string, bool) {
	v, ok := w.Entities()[name]
	return v, ok && v != ""
}

// PendingClarify is the clarifying question the assistant asked on its LAST turn, if it asked one.
//
// ONLY THE LAST TURN COUNTS. A clarify two questions ago has been overtaken, the person answered
// something else, or changed the subject, and treating a stale clarify as live is how an assistant
// answers a question nobody is still asking.
func (w Window) PendingClarify() (*Clarify, bool) {
	for i := len(w.Turns) - 1; i >= 0; i-- {
		m := w.Turns[i]
		if m.Role == RoleUser {
			// The person has spoken since; there is no live clarify to complete.
			return nil, false
		}
		if m.Clarify != nil && len(m.Clarify.Options) > 0 {
			return m.Clarify, true
		}
	}
	return nil, false
}

// LastUserText is the previous thing the PERSON said (not the current question). Used only to make
// an honest refusal readable; never to resolve an entity.
func (w Window) LastUserText() string {
	for i := len(w.Turns) - 1; i >= 0; i-- {
		if w.Turns[i].Role == RoleUser {
			return w.Turns[i].Text
		}
	}
	return ""
}
