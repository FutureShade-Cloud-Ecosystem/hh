-- 0381: the messaging sync feeds (House Messages core, roles roadmap Lane E).
-- Owner: internal/messaging.
--
-- WHAT THIS DOES. The four sync scopes the contract already declares
-- (channels, messages, acks, notify_prefs; core/internal/sync/registry.go)
-- have answered 501 since the Phase D split: 0213 gave their tables the seq,
-- deleted_at and idempotency_key columns but left every seq NULL (carried
-- rows keep NULL until the unified core owns the write path), and the two
-- per-user tables had no row id the engine's update and delete legs address.
-- The messaging module IS the unified core for these tables (every write is
-- this module's), so this migration finishes what 0213 started:
--
--   seq   becomes NOT NULL then GENERATED BY DEFAULT AS IDENTITY on each feed
--         table (identity requires NOT NULL; 0213 left the column nullable
--         and NULL on every row, so the NULLs become 0 first and every row
--         then takes a fresh value from the new sequence): every
--         INSERT is stamped by the table itself (the module's INSERT column
--         lists are untouched), and the existing rows are backfilled from
--         the new sequence. A write that changes a row the feed already
--         served (the approval status stamp, a supersede, a rollup edit, an
--         ack or prefs upsert, a membership change) draws a fresh value
--         explicitly, so a device's cached copy is told to refresh. The
--         identity form keeps every existing statement compiling: a plain
--         DEFAULT-less BIGINT would leave every future INSERT NULL-seq and
--         invisible to the feeds.
--   id    a uuid row id for msg_acks and msg_notification_prefs, whose keys
--         are composite; existing rows are backfilled by the column default.
--   indexes for the four feeds' pull shapes and the FindApplied dedup
--         (idempotency_key is 0213's own UUID column, stamped by the sync
--         store's write paths; the REST writes leave it NULL).
--
-- WHY IDENTITY AND NOT scope_sequences (the allocator convention most sync
-- stores draw from): scope_sequences is identity-owned, and the messaging
-- module's files hold no tablegate allowance to write it (the allowlist is
-- frozen for this lane; a new cross-module table access is exactly what the
-- census refuses). A table-owned identity column needs no cross-module
-- counter at all, hands the seq out inside the INSERT the module already
-- runs, and carries the 0078 precedent (audit_log's causal feed key, the
-- same reasoning recorded there: a DB-assigned strictly increasing key,
-- backfilled on existing rows in no particular order, and no consumer relies
-- on the historical order).
--
-- THE FENCE, STATED PLAINLY. The messaging tables carry no org column and
-- the GLOBAL channels cross orgs by design (a company-wide #office is one
-- row for every org the platform hosts), so an org fence cannot be proven on
-- these rows and was the recorded stop. The stores this migration serves
-- fence STRONGER than org on every read: each feed answers only the caller's
-- own world (its channels, their messages, its own acks and prefs), resolved
-- through the linked ERP user the sync filter's Actor names. A row outside
-- the caller's membership is the same as absent, whatever org it belongs to.
--
-- Forward only, additive only: no table is created, no column is dropped,
-- every new index arrives empty beside its predicate.

-- channels: the pull-only reference feed of rooms.
UPDATE msg_channels SET seq = 0 WHERE seq IS NULL;
ALTER TABLE msg_channels ALTER COLUMN seq SET NOT NULL;
ALTER TABLE msg_channels ALTER COLUMN seq ADD GENERATED BY DEFAULT AS IDENTITY;
UPDATE msg_channels SET seq = nextval(pg_get_serial_sequence('msg_channels', 'seq'));
CREATE INDEX idx_msg_channels_seq ON msg_channels (seq);

-- messages: the per-caller message feed (TEXT, EVENT and APPROVAL alike).
UPDATE msg_messages SET seq = 0 WHERE seq IS NULL;
ALTER TABLE msg_messages ALTER COLUMN seq SET NOT NULL;
ALTER TABLE msg_messages ALTER COLUMN seq ADD GENERATED BY DEFAULT AS IDENTITY;
UPDATE msg_messages SET seq = nextval(pg_get_serial_sequence('msg_messages', 'seq'));
CREATE INDEX idx_msg_messages_seq ON msg_messages (seq);
CREATE UNIQUE INDEX uq_msg_messages_idempotency_key ON msg_messages (idempotency_key) WHERE idempotency_key IS NOT NULL;

-- acks: one row per (message, user); the feed serves the caller's own rows.
ALTER TABLE msg_acks ADD COLUMN id UUID NOT NULL DEFAULT gen_random_uuid();
UPDATE msg_acks SET seq = 0 WHERE seq IS NULL;
ALTER TABLE msg_acks ALTER COLUMN seq SET NOT NULL;
ALTER TABLE msg_acks ALTER COLUMN seq ADD GENERATED BY DEFAULT AS IDENTITY;
UPDATE msg_acks SET seq = nextval(pg_get_serial_sequence('msg_acks', 'seq'));
CREATE UNIQUE INDEX uq_msg_acks_id ON msg_acks (id);
CREATE INDEX idx_msg_acks_user_seq ON msg_acks (user_id, seq);
CREATE UNIQUE INDEX uq_msg_acks_idempotency_key ON msg_acks (idempotency_key) WHERE idempotency_key IS NOT NULL;

-- notify_prefs: same shape, one row per (channel, user).
ALTER TABLE msg_notification_prefs ADD COLUMN id UUID NOT NULL DEFAULT gen_random_uuid();
UPDATE msg_notification_prefs SET seq = 0 WHERE seq IS NULL;
ALTER TABLE msg_notification_prefs ALTER COLUMN seq SET NOT NULL;
ALTER TABLE msg_notification_prefs ALTER COLUMN seq ADD GENERATED BY DEFAULT AS IDENTITY;
UPDATE msg_notification_prefs SET seq = nextval(pg_get_serial_sequence('msg_notification_prefs', 'seq'));
CREATE UNIQUE INDEX uq_msg_notification_prefs_id ON msg_notification_prefs (id);
CREATE INDEX idx_msg_notification_prefs_user_seq ON msg_notification_prefs (user_id, seq);
CREATE UNIQUE INDEX uq_msg_notification_prefs_idempotency_key ON msg_notification_prefs (idempotency_key) WHERE idempotency_key IS NOT NULL;
